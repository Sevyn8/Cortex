#!/usr/bin/env node
/**
 * Bi-temporal table scaffold (F03 Slice A).
 *
 * Generates a recipe-applied SQL DDL block for a new tenant-scoped
 * domain table per ADR-DB-001 + f03-slice-A-scope.md. Writes to stdout;
 * operator redirects to a chosen migration file path + appends the
 * journal entry manually (ADR-DB-001 §Implementation Notes — high-water
 * mark discipline). The scaffold deliberately does NOT touch
 * services/foundation/migrations/meta/_journal.json.
 *
 * Output uses the post-0006 trigger binding
 * (`BEFORE INSERT OR UPDATE OR DELETE`) — the canonical form. Migration
 * 0002's header recipe (which says BEFORE UPDATE OR DELETE only) is
 * stale; corrected in this same Slice A commit.
 *
 * Args (env vars; matches `make image-bootstrap` pattern):
 *   TABLE          required  table name (snake_case; e.g., `retail_product`)
 *   BUSINESS_KEY   required  business-key column name (e.g., `external_sku`)
 *   WITH_WRAPPERS  optional  y|n (default y) — whether to emit per-table
 *                            as_of_valid / as_of_latest / history wrappers
 *
 * Per Q-NEW-F03A-1 synthesis: WITH_WRAPPERS=y (default) generates the 3
 * wrappers over cortex.at_time_t for the table. Locks per-table query
 * shape; closes roadmap §5.2 on a per-table basis as scaffolds run. Use
 * WITH_WRAPPERS=n only when the access pattern hasn't been designed yet
 * AND the table needs to ship bi-temporal for future-compat. See
 * CLAUDE.md "Bi-temporal table convention" for the full flag rationale.
 *
 * Usage (wrapped by Makefile target `db-scaffold-bitemporal`):
 *   make db-scaffold-bitemporal TABLE=retail_product BUSINESS_KEY=external_sku
 *   make db-scaffold-bitemporal TABLE=foo BUSINESS_KEY=bar WITH_WRAPPERS=n
 */
const TABLE_RE = /^[a-z][a-z0-9_]{0,62}$/;
const COLUMN_RE = /^[a-z][a-z0-9_]{0,62}$/;

function fail(msg) {
  console.error(`scaffold-bitemporal: ${msg}`);
  process.exit(2);
}

const TABLE = process.env.TABLE;
const BUSINESS_KEY = process.env.BUSINESS_KEY;
const WITH_WRAPPERS = (process.env.WITH_WRAPPERS ?? 'y').toLowerCase();

if (!TABLE || !TABLE_RE.test(TABLE)) {
  fail(`TABLE env var required (snake_case identifier; got ${JSON.stringify(TABLE)})`);
}
if (!BUSINESS_KEY || !COLUMN_RE.test(BUSINESS_KEY)) {
  fail(
    `BUSINESS_KEY env var required (snake_case identifier; got ${JSON.stringify(BUSINESS_KEY)})`,
  );
}
if (WITH_WRAPPERS !== 'y' && WITH_WRAPPERS !== 'n') {
  fail(`WITH_WRAPPERS must be y or n (got ${JSON.stringify(WITH_WRAPPERS)})`);
}

const t = TABLE;
const bk = BUSINESS_KEY;

const header = `-- Migration: ${t} bi-temporal table (F03-style; ADR-DB-001 recipe).
--
-- Generated by scripts/scaffold-bitemporal.mjs (F03 Slice A).
-- Operator must:
--   1. Save this output as services/foundation/migrations/<idx>_${t}.sql
--   2. Append a journal entry to services/foundation/migrations/meta/_journal.json
--      (use Date.now() for "when"; matches existing entries' shape).
--   3. Apply via \`make db-migrate-{env}\`.
--
-- Recipe assumes the runtime ships migrations 0001 (extensions),
-- 0002 (cortex.cortex_scd_trigger + cortex.at_time_t), and 0006 (ms-
-- precision normalization). Trigger binding is post-0006:
-- BEFORE INSERT OR UPDATE OR DELETE — the INSERT branch normalizes
-- timestamps to ms quantum; UPDATE / DELETE branches close the prior row.

CREATE TABLE ${t} (
  id            uuid       PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id     uuid       NOT NULL,
  ${bk}         text       NOT NULL,
  -- Domain columns: add here. NO GENERATED columns (incompatible with
  -- the cortex_scd_trigger UPDATE branch's $1::row INSERT).
  valid_time    tstzrange  NOT NULL,
  txn_time      tstzrange  NOT NULL DEFAULT tstzrange(now(), NULL)
);
--> statement-breakpoint

CREATE TRIGGER ${t}_scd
  BEFORE INSERT OR UPDATE OR DELETE ON ${t}
  FOR EACH ROW EXECUTE FUNCTION cortex.cortex_scd_trigger();
--> statement-breakpoint

ALTER TABLE ${t}
  ADD CONSTRAINT ${t}_business_key_no_overlap
  EXCLUDE USING gist (
    tenant_id  WITH =,
    ${bk}      WITH =,
    valid_time WITH &&
  ) WHERE (upper(txn_time) IS NULL);
--> statement-breakpoint

CREATE INDEX ${t}_temporal_gist
  ON ${t}
  USING gist (tenant_id, valid_time, txn_time);
--> statement-breakpoint

CREATE INDEX ${t}_tenant_current
  ON ${t} (tenant_id)
  WHERE upper(txn_time) IS NULL;
`;

const wrappers = `--> statement-breakpoint

-- Per-table query wrappers over cortex.at_time_t. Generated by scaffold
-- (WITH_WRAPPERS=y; the default). Closes roadmap §5.2 on a per-table
-- basis. See ADR-DB-001 §Implementation Notes for the wrapper pattern.

CREATE FUNCTION cortex.${t}_as_of_valid(p_id uuid, p_ts timestamptz)
  RETURNS SETOF ${t}
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  AS $$
    SELECT *
    FROM ${t}
    WHERE id = p_id
      AND cortex.at_time_t(valid_time, txn_time, p_ts, now())
  $$;
--> statement-breakpoint

CREATE FUNCTION cortex.${t}_as_of_latest(p_id uuid)
  RETURNS SETOF ${t}
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  AS $$
    SELECT *
    FROM ${t}
    WHERE id = p_id
      AND upper(txn_time) IS NULL
  $$;
--> statement-breakpoint

CREATE FUNCTION cortex.${t}_history(p_id uuid)
  RETURNS SETOF ${t}
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  AS $$
    SELECT *
    FROM ${t}
    WHERE id = p_id
    ORDER BY lower(txn_time) ASC
  $$;
`;

let out = header;
if (WITH_WRAPPERS === 'y') {
  out += wrappers;
}

process.stdout.write(out);
